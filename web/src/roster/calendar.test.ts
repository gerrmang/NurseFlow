import { describe, expect, it } from 'vitest'
import { shiftTime } from './calendar'

describe('shiftTime', () => {
  it.each(['Z', 'UTC', 'GMT', 'UT', '+00:00', 'UTC-00:00'])(
    '%s 고정 시간대로 자정을 넘는 근무를 표시한다', timeZone => {
      expect(shiftTime('2026-11-01T22:00:00Z', '2026-11-02T07:00:00Z', timeZone))
        .toBe('22:00 → 2026-11-02 07:00')
    },
  )

  it.each(['UTC+09:00', 'GMT+09:00', 'UT+09:00', '+09:00', '+9', '+09', '+0900', '+090000', '+09:00:00', 'Asia/Seoul'])(
    '%s 병동의 현지 날짜로 월 경계를 표시한다', timeZone => {
      expect(shiftTime('2026-11-30T13:00:00Z', '2026-11-30T22:00:00Z', timeZone))
        .toBe('22:00 → 2026-12-01 07:00')
    },
  )

  it('음수 오프셋으로 전날에 시작하는 근무를 표시한다', () => {
    expect(shiftTime('2026-01-01T03:00:00Z', '2026-01-01T12:00:00Z', 'UTC-05:30'))
      .toBe('21:30 → 2026-01-01 06:30')
  })

  it('초 단위 오프셋을 날짜 경계에도 적용한다', () => {
    expect(shiftTime('2026-11-01T14:59:00Z', '2026-11-01T14:59:45Z', 'UTC+09:00:30'))
      .toBe('23:59 → 2026-11-02 00:00')
  })

  it('같은 현지 날짜에 끝나는 근무에는 날짜를 붙이지 않는다', () => {
    expect(shiftTime('2026-11-01T22:00:00Z', '2026-11-02T07:00:00Z', 'UTC+09:00'))
      .toBe('07:00 → 16:00')
  })

  it('지역 시간대의 서머타임 전환을 유지한다', () => {
    expect(shiftTime('2026-03-08T06:30:00Z', '2026-03-08T07:30:00Z', 'America/New_York'))
      .toBe('01:30 → 03:30')
  })
})
